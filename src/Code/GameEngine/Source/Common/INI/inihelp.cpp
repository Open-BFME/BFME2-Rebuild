void iniParseScienceVectorVector(INI *ini, void *, void *store, const void *)
{
	typedef _STL::vector<ScienceType> ScienceList;
	_STL::vector<ScienceList> *lists = static_cast<_STL::vector<ScienceList> *>(store);
	lists->resize(1);
	ScienceList *current = &lists->back();
	for (const char *token = ini->getNextTokenOrNull(0); token != 0; token = ini->getNextTokenOrNull(0)) {
		if (INICRT::_strcmpi(token, "None") == 0) {
			current->erase(current->begin(), current->end());
			break;
		}
		if (INICRT::_strcmpi(token, "OR") == 0) {
			if (current->empty())
				break;
			lists->push_back(ScienceList());
			current = &lists->back();
		} else {
			current->push_back(INI::scanScience(token));
		}
	}
	if (current->empty())
		lists->erase(lists->begin(), lists->end());
}
