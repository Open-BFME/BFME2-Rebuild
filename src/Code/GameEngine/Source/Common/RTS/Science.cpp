bool ScienceStore::playerHasPrereqsForScience(const ScienceQueryInterface *player, ScienceType science) const
{
	const ScienceInfo *info = findScienceInfo(science);
	if (info != 0)
	{
		if (info->m_prerequisites.size() == 0)
			return true;
		for (_STL::vector<_STL::vector<ScienceType> >::const_iterator group = info->m_prerequisites.begin(); group != info->m_prerequisites.end(); ++group)
		{
			for (_STL::vector<ScienceType>::const_iterator it = group->begin(); ; ++it)
			{
				if (it == group->end())
					return true;
				ScienceType required = *it;
				if (!player->queryHasScience(required))
					break;
			}
		}
	}
	return false;
}

