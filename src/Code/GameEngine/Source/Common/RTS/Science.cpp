// FUNCTION: BFME2 0x001FF3DC size=86 name=?getSciencePurchaseCost@ScienceStore@@QBEHW4ScienceType@@@Z evidence=N:ledger tier=B hypothesis:cohesion
int ScienceStore::getSciencePurchaseCost(ScienceType science) const
{
	const ScienceInfo *info = findScienceInfo(science);
	if (info)
	{
		GameLogic *logic = TheGameLogic;
		const Bool multiplayer = logic->isInMultiplayerGame();
		Int mode = 0;
		if (!multiplayer)
			mode = logic->getGameMode();
		if (multiplayer || mode == 2 || (mode == 3 && TheRecorder && TheRecorder->isMultiplayer()))
			return info->m_unk0x2C;
		return info->m_unk0x28;
	}
	return 0;
}

