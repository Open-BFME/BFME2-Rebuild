// FUNCTION: BFME2 0x003B15D6 size=541 name=?parseSpecialPowerDefinition@SpecialPowerStore@@SAXPAVINI@@@Z evidence=N:ledger tier=B hypothesis:K

void SpecialPowerStore::parseSpecialPowerDefinition(INI *ini)
{
	AsciiString name(ini->getNextToken());
	SpecialPowerTemplate *existing = TheSpecialPowerStore->findSpecialPowerTemplatePrivate(name);
	SpecialPowerTemplate *power;

	if (ini->getLoadType() == INI_LOAD_CREATE_OVERRIDES)
	{
		if (existing != 0)
		{
			// A new override hangs off the end of the existing template's chain.
			SpecialPowerTemplate *last = (SpecialPowerTemplate *)existing->friend_getFinalOverride();
			power = new SpecialPowerTemplate;
			g_00E01EA8 = 1;
			*power = *last;
			g_00E01EA8 = 0;
			last->setNextOverride(power);
			power->markAsOverride();
		}
		else
		{
			power = new SpecialPowerTemplate;
			const SpecialPowerTemplate *defaults = TheSpecialPowerStore->findSpecialPowerTemplate(AsciiString("DefaultSpecialPower"));
			if (defaults != 0)
			{
				g_00E01EA8 = 1;
				*power = *defaults;
				g_00E01EA8 = 0;
			}
			++TheSpecialPowerStore->m_nextId;
			power->setNameAndId(name, TheSpecialPowerStore->m_nextId);
			power->markAsOverride();
			TheSpecialPowerStore->m_templates.push_back(power);
		}
	}
	else
	{
		if (existing != 0)
			throw INIException(3, "Special power '%s' already defined", name.str());

		power = new SpecialPowerTemplate;
		const SpecialPowerTemplate *defaults = TheSpecialPowerStore->findSpecialPowerTemplate(AsciiString("DefaultSpecialPower"));
		if (defaults != 0)
		{
			g_00E01EA8 = 1;
			*power = *defaults;
			g_00E01EA8 = 0;
		}
		++TheSpecialPowerStore->m_nextId;
		power->setNameAndId(name, TheSpecialPowerStore->m_nextId);
		TheSpecialPowerStore->m_templates.push_back(power);
	}

	if (power != 0)
		ini->initFromINI(power, SpecialPowerTemplate::m_fieldParseTable);
}

