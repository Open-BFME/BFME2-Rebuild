// FUNCTION: BFME2 0x003B1244 size=227 name=?canUseSpecialPower@SpecialPowerStore@@QAE_NPAVObject@@PBVSpecialPowerTemplate@@@Z evidence=N:ledger tier=B hypothesis:K

Bool SpecialPowerStore::canUseSpecialPower(Object *obj, const SpecialPowerTemplate *power)
{
	if (obj == 0 || power == 0)
		return false;
	if (obj->getSpecialPowerModule(power) == 0)
		return false;
	// Slot 18 of the module interface, called with a null location.
	if (!obj->getSpecialPowerModule(power)->rva0049466D(0))
		return false;

	Player *player = obj->getControllingPlayer();
	_STL::vector<ScienceType> required = power->rva0029FCB4();
	if (player != 0 && !required.empty())
	{
		if (!player->hasAnyRequiredSciences(required))
			return false;
	}
	if (!obj->getControllingPlayer()->rva002A9ED9(power))
		return false;
	if (obj->m_status.test(&power->m_preventActivationConditions))
		return false;
	return true;
}

