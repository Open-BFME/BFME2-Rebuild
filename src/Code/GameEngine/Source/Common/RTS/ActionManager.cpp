Bool ActionManager::canTransferSuppliesAt(const Object *obj, const Object *transferDest)
{
	if (obj == NULL || transferDest == NULL)
		return FALSE;

	if (transferDest->isEffectivelyDead())
		return FALSE;

	// Nothing can be done with things that are under construction, or sold.
	if (obj->testStatus(OBJECT_STATUS_UNDER_CONSTRUCTION) || transferDest->testStatus(OBJECT_STATUS_UNDER_CONSTRUCTION))
		return FALSE;

	if (transferDest->testStatus(OBJECT_STATUS_SOLD))
		return FALSE;

	// Only something with a supply truck interface carries supplies.
	const AIUpdateInterface *ai = obj->getAI();
	if (ai == NULL)
		return FALSE;

	const SupplyTruckAIInterface *supplyTruck = ai->getSupplyTruckAIInterface();
	if (supplyTruck == NULL)
		return FALSE;

	// A warehouse must have boxes left and must not be an enemy.
	static NameKeyType warehouseKey = TheNameKeyGenerator->nameToKey("SupplyWarehouseDockUpdate");
	SupplyWarehouseDockUpdate *warehouse = (SupplyWarehouseDockUpdate *)transferDest->findUpdateModule(warehouseKey);
	if (warehouse)
		if (warehouse->m_boxesStored == 0 || transferDest->getRelationship(obj) == ENEMIES)
			return FALSE;

	// A supply center needs boxes carried, and the same controlling player.
	static NameKeyType centerKey = TheNameKeyGenerator->nameToKey("SupplyCenterDockUpdate");
	SupplyCenterDockUpdate *center = (SupplyCenterDockUpdate *)transferDest->findUpdateModule(centerKey);
	if (center)
		if (supplyTruck->getNumberBoxes() == 0 || transferDest->getControllingPlayer() != obj->getControllingPlayer())
			return FALSE;

	if (warehouse == NULL && center == NULL)
		return FALSE;

	if (!supplyTruck->isAvailableForSupplying())
		return FALSE;

	// A human player cannot act on a target that is in the shroud.
	Player *player = obj->getControllingPlayer();
	if (player && player->m_playerType == PLAYER_HUMAN
		&& transferDest->getShroudStatusForPlayer(player->getPlayerIndex()) == 4)
		return FALSE;

	return TRUE;
}

