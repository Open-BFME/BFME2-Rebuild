{
	if (!(player && target))
		return false;

	if (target->isEffectivelyDead())
		return false;

	if (!target->getTemplate()->isKindOf(KINDOF_STRUCTURE))
		return false;

	ContainModuleInterface *cmi = target->getContain();
	if (cmi == NULL)
		return false;

	if (!cmi->isGarrisonable())
		return false;

	if (player == target->getControllingPlayer())
		return true;

	if (player->getRelationship(target->getTeam()) == NEUTRAL)
		return cmi->getCount(false) == 0;

	return false;
}

