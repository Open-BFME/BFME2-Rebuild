void PlayerList::newGame()
{
	Int i;

	TheTeamFactory->clear();
	init();

	Bool setLocal = false;
	for (i = 0; i < TheSidesList->getNumSides(); i++)
	{
		Dict *dict = &TheSidesList->getSideInfo(i)->m_dict;
		AsciiString pname = dict->getAsciiString(TheKey_playerName.key());
		if (pname.isEmpty())
			continue;

		Player *player = m_players[m_playerCount++];
		player->initFromDict(dict);

		Bool exists;
		if (dict->getBool(TheKey_multiplayerIsLocal.key(), &exists))
		{
			setLocalPlayer(player);
			setLocal = true;
		}

		if (!setLocal && !TheNetwork && dict->getBool(TheKey_playerIsHuman.key()))
		{
			setLocalPlayer(player);
			setLocal = true;
		}

		player->setBuildList(TheSidesList->getSideInfo(i)->m_pBuildList);
		TheSidesList->getSideInfo(i)->m_pBuildList = 0;
	}

	if (!setLocal)
	{
		for (i = 0; i < TheSidesList->getNumSides(); i++)
		{
			Player *player = getNthPlayer(i);
			if (player != getNeutralPlayer())
			{
				player->setPlayerType(PLAYER_HUMAN, false);
				setLocalPlayer(player);
				setLocal = true;
				break;
			}
		}
	}

	TheTeamFactory->initFromSides(TheSidesList);

	for (i = 0; i < TheSidesList->getNumSides(); i++)
	{
		Dict *dict = &TheSidesList->getSideInfo(i)->m_dict;
		Player *player = findPlayerWithNameKey(TheNameKeyGenerator->nameToKey(dict->getAsciiString(TheKey_playerName.key())));

		AsciiString tok;

		AsciiString enemies = dict->getAsciiString(TheKey_playerEnemies.key());
		while (enemies.nextToken(&tok, 0))
		{
			Player *namedPlayer = findPlayerWithNameKey(TheNameKeyGenerator->nameToKey(tok));
			if (namedPlayer)
				player->setPlayerRelationship(namedPlayer, ENEMIES);
		}

		AsciiString allies = dict->getAsciiString(TheKey_playerAllies.key());
		while (allies.nextToken(&tok, 0))
		{
			Player *namedPlayer = findPlayerWithNameKey(TheNameKeyGenerator->nameToKey(tok));
			if (namedPlayer)
				player->setPlayerRelationship(namedPlayer, ALLIES);
		}

		player->setPlayerRelationship(player, ALLIES);
		if (player != getNeutralPlayer())
			player->setPlayerRelationship(getNeutralPlayer(), NEUTRAL);

		player->setDefaultTeam();
	}
}

