// FUNCTION: BFME2 0x00005923 size=124 name=?toAngle@Coord2D@@QBEMXZ evidence=N:ledger tier=B hypothesis:K
float Coord2D::toAngle() const
{
	const float len = length();
	if (len == 0.0f)
		return 0.0f;

	const float ratio = x / len;
	// bound it in case of numerical error
	float c;
	if (ratio < -1.0f)
		c = -1.0f;
	else if (ratio > 1.0f)
		c = 1.0f;
	else
		c = ratio;

	return y < 0.0f ? -ACos(c) : ACos(c);
}

