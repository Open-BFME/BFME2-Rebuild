// WideCharCompare's two workers (retail 0x000052F8 / 0x00005344, rows in object
// unknown just before this unit; the wide range workers below call them): a
// plain loop, and the same through msvcr71's towlower (IAT 0x00BBA68C).
int WideCharCompare::compare(const unsigned short *a, const unsigned short *b, int count) const
{
	for (; count > 0; --count)
	{
		if (*a != *b)
			return *a - *b;
		++a;
		++b;
	}
	return 0;
}

int WideCharCompare::compareNoCase(const unsigned short *a, const unsigned short *b, int count) const
{
	for (; count > 0; --count)
	{
		unsigned short ca = StringCRT::towlower(*a);
		unsigned short cb = StringCRT::towlower(*b);
		if (ca != cb)
			return ca - cb;
		++a;
		++b;
	}
	return 0;
}

