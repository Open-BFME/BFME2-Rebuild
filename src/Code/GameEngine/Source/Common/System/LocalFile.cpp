// FUNCTION: BFME2 0x00605FDF size=144 name=?convertToRAMFile@LocalFile@@UAEPAVFile@@XZ evidence=N:ledger tier=B hypothesis:Z
File *LocalFile::convertToRAMFile()
{
	RAMFile *ramFile = new RAMFile;
	if (ramFile->open(this))
	{
		if (m_deleteOnClose)
		{
			ramFile->deleteOnClose();
			close();
		}
		else
		{
			close();
			::delete this;
		}
		return ramFile;
	}
	ramFile->close();
	::delete ramFile;
	return this;
}

