	int count = 0;
	int bytesRead;
	do {
		if (buffer && count < size - 1) {
			bytesRead = _read(m_fd, buffer + count, 1);
			ch = buffer[count];
		} else {
			bytesRead = _read(m_fd, &ch, 1);
		}
		++count;
	} while (bytesRead != 0 && ch != '\n');
	if (buffer) {
		if (count < size)
			buffer[count] = 0;
		else
			buffer[size] = 0;
	}
