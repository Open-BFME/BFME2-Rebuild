// FUNCTION: BFME2 0x002DC4B8 size=115 name=?rva002DC4B8@GameState@@QAEXPAXI@Z evidence=?:placeholder tier=A
void GameState::removePostProcessSnapshotsSince(void *, UnsignedInt sequence)
{
	_STL::list<PostProcessEntry>::iterator it = m_postProcessPairs.begin();
	while (it != m_postProcessPairs.end())
	{
		PostProcessEntry &entry = *it;
		if (entry.flag >= sequence)
		{
			it = m_postProcessPairs.erase(it);
			for (_STL::list<Snapshot *>::iterator p = m_postProcessList.begin(); p != m_postProcessList.end(); ++p)
			{
				if (*p == entry.snapshot)
				{
					m_postProcessList.erase(p);
					break;
				}
			}
		}
		else
			++it;
	}
}

