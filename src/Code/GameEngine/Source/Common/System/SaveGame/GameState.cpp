// FUNCTION: BFME2 0x002DCE24 size=327 name=?xferSaveData@GameState@@QAEXPAVXfer@@W4SnapshotType@@@Z evidence=N:ledger tier=A
void GameState::xferSaveData(Xfer *xfer, SnapshotType which)
{
	if (xfer->IsStoring())
	{
		AsciiString blockName;
		_STL::list<SnapshotBlock> &blocks = m_snapshotLists[which];
		for (_STL::list<SnapshotBlock>::iterator it = blocks.begin(); it != blocks.end(); ++it)
		{
			SnapshotBlock *blockInfo = &*it;
			blockName = blockInfo->name;
			*xfer == blockName;
			try
			{
				xfer->BeginBlock("Snapshot");
				*xfer == *blockInfo->snapshot;
				xfer->EndBlock();
			}
			catch (...)
			{
				throw;
			}
		}
		AsciiString eofToken = SAVE_FILE_EOF;
		*xfer == eofToken;
	}
	else
	{
		AsciiString token;
		Bool done = false;
		while (!done)
		{
			*xfer == token;
			if (token.compareNoCase(SAVE_FILE_EOF) == 0)
			{
				done = true;
			}
			else
			{
				SnapshotBlock *blockInfo = findBlockInfoByToken(token, which);
				if (blockInfo == 0)
				{
					xfer->SkipBlock("Snapshot");
					continue;
				}
				try
				{
					xfer->BeginBlock("Snapshot");
					*xfer == *blockInfo->snapshot;
					xfer->EndBlock();
				}
				catch (...)
				{
					throw;
				}
			}
		}
	}
}

// FUNCTION: BFME2 0x002DCF6C size=130 name=?addPostProcessSnapshot@GameState@@QAEXPAVSnapshot@@I@Z evidence=N:ledger tier=A
