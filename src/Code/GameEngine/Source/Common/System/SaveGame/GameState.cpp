{
	if (snapshot == 0)
		return;
	const char *name = snapshot->GetSnapshotName();
	Snapshot *postCopy = snapshot;
	PostProcessEntry entry;
	if (name != 0 && strcmp(name, "Object") == 0)
	{
		m_postProcessList.push_front(postCopy);
		entry.snapshot = snapshot;
		entry.flag = flag;
		m_postProcessPairs.push_back(entry);
	}
	else
	{
		if (name != 0 && strcmp(name, "Weapon") == 0)
			return;
		m_postProcessList.push_back(postCopy);
		entry.snapshot = snapshot;
		entry.flag = flag;
		m_postProcessPairs.push_back(entry);
	}
}

