UnsignedInt __fastcall randomValue(UnsignedInt *seed)
{
	UnsignedInt ax;
	UnsignedInt c = 0;

	ADC(ax, seed[5], seed[4], c);
	seed[4] = ax;

	ADC(ax, ax, seed[3], c);
	seed[3] = ax;

	ADC(ax, ax, seed[2], c);
	seed[2] = ax;

	ADC(ax, ax, seed[1], c);
	seed[1] = ax;

	ADC(ax, ax, seed[0], c);
	seed[0] = ax;

	if (!++seed[5])
	{
		if (!++seed[4])
		{
			if (!++seed[3])
			{
				if (!++seed[2])
				{
					if (!++seed[1])
					{
						++seed[0];
						++ax;
					}
				}
			}
		}
	}
	return ax;
}

