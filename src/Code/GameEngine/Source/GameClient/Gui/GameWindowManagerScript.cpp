// FUNCTION: BFME2 0x0031732D size=255 name=?parseLayoutBlock@@YA_NPAVFile@@PADIPAVWindowLayoutInfo@@@Z evidence=N:ledger

Bool parseLayoutBlock(File *inFile, char *buffer, UnsignedInt version, WindowLayoutInfo *info)
{
	LayoutScriptParse *entry;
	char token[256];

	AsciiString word;
	if (inFile->scanString(word) == false)
	{
		return false;
	}

	if (word.compare("STARTLAYOUTBLOCK") != 0)
	{
		return false;
	}

	while (true)
	{
		inFile->scanString(word);

		if (word.compare("ENDLAYOUTBLOCK") == 0)
		{
			break;
		}

		for (entry = layoutScriptTable; entry && entry->name; entry++)
		{
			if (word.compare(entry->name) == 0)
			{
				char *c;

				readUntilSemicolon(inFile, buffer, 2048);

				c = strtok(buffer, " =");

				_mbscpy(token, word.str());

				if (entry->parse(token, c, version, info) == false)
					return false;

				break;	// exit for
			}
		}
	}

	return true;
}

