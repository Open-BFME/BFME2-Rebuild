static void readUntilSemicolon(File *fp, char *buffer, int maxBufLen)
{
	int i = 0;
	Bool start = true;

	while (i < maxBufLen)
	{
		fp->read(buffer + i, 1);

		// whitespace collapses to single spaces; leading whitespace is dropped
		if (isspace(buffer[i]))
		{
			if (start == false)
				buffer[i++] = ' ';
		}
		else
		{
			start = false;

			if (buffer[i] == ';')
			{
				buffer[i] = '\000';
				return;
			}

			i++;
		}
	}

	buffer[maxBufLen - 1] = '\000';
}

