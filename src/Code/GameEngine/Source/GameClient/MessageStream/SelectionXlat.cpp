bool CanSelectDrawable(const Drawable *draw, bool dragSelecting)
{
	if (!draw || !draw->getObject())
	{
		return false;
	}
	const Object *obj = draw->getObject();

	if (obj->isEffectivelyDead() && !obj->getTemplate()->m_keepSelectableWhenDead && !obj->isKindOf(KINDOF_ALWAYS_SELECTABLE))
	{
		return false;
	}

	if (!obj->isKindOf(KINDOF_SELECTABLE) && obj->isKindOf(KINDOF_FORCEATTACKABLE))
	{
		return false;
	}

	if (obj->isKindOf(KINDOF_MOVE_ONLY))
	{
		return false;
	}

	if (draw->isDrawableEffectivelyHidden())
	{
		return false;
	}

	GameWindow *window = NULL;
	if (TheWindowManager)
	{
		const Coord3D *c = draw->getPosition();
		ICoord2D c2;
		TheTacticalView->worldToScreen(c, &c2);
		window = TheWindowManager->getWindowUnderCursor(c2.x, c2.y, false);
	}

	while (window)
	{
		if (!(window->winGetStatus() & WIN_STATUS_SEE_THRU))
		{
			return false;
		}

		window = window->winGetParent();
	}

	if (dragSelecting)
	{
		if (draw->isKindOf(KINDOF_STRUCTURE))
		{
			return false;
		}

		if (draw->isKindOf(KINDOF_DOZER) && obj->testModelConditionState((ModelConditionFlagType)73))
		{
			return false;
		}
	}

	if (obj->testStatus(OBJECT_STATUS_UNSELECTABLE))
	{
		return false;
	}

	if (obj->isMasked())
	{
		return false;
	}

	if (!obj->isSelectable())
	{
		return false;
	}

	if (dragSelecting && !obj->isLocallyControlled())
	{
		return false;
	}

	return true;
}

