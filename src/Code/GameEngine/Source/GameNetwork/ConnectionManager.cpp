Bool ConnectionManager::isDuplicateCommand(NetCommandMsg *msg)
{
	if (m_localSlot == m_packetRouterSlot)
	{
		if (msg->getPlayerID() != m_packetRouterSlot && msg->getPlayerID() < 8 &&
			DoesCommandRequireACommandID(msg->getNetCommandType()))
		{
			if (!m_commandHistory[msg->getPlayerID()].accept(msg->getID(), TheGameLogic->getFrame() + 1))
				return true;
		}
	}
	else
	{
		if (msg->getPlayerID() == m_packetRouterSlot && DoesCommandRequireACommandID(msg->getNetCommandType()))
		{
			if (!m_commandHistory[8].accept(msg->getID(), msg->getExecutionFrame()))
				return true;
		}
	}
	return false;
}

