void NAT::gotTargetMangledPort(Int slot, UnsignedShort mangledPort, Int mangledAddress)
{
	if (m_connectionState == 4 && m_previousConnectionState == 4)
		return;
	GameSlot *targetSlot = m_slotList[m_targetSlot];
	if (targetSlot == 0)
	{
		setCurrentConnectionState(5);
		return;
	}
	GameSlot *localSlot = m_slotList[m_localSlot];
	if (localSlot == 0)
	{
		setCurrentConnectionState(5);
		return;
	}
	if (slot != m_targetSlot)
		return;
	if (m_active == 0)
	{
		m_unk0x25 = true;
	}
	else
	{
		m_unk0x25 = true;
		m_addresses[m_targetSlot]->m_port = mangledPort;
		if (m_addresses[m_localSlot]->m_ip == m_addresses[m_targetSlot]->m_ip)
			m_addresses[m_targetSlot]->m_ip = mangledAddress;
	}
	if (m_unk0x24 == 0)
		return;
	m_transport->setDestAddrToSocket(m_targetSlot, m_addresses[m_targetSlot]);
	if (m_connectionState != 2)
		return;
	if ((localSlot->m_unk0x40 & 8) != 0)
	{
		if (m_beenProbed != 1 && (targetSlot->m_unk0x40 & 8) == 0)
			return;
	}
	sendAProbeToTarget();
	setCurrentConnectionState(3);
}

// FUNCTION: BFME2 0x005A879B size=551 name=?connectionUpdate@NAT@@QAEHXZ evidence=N:ledger tier=A
Int NAT::connectionUpdate()
{
	if (m_targetSlot < 0 || m_targetSlot >= 8)
	{
		m_connectionState = 4;
		return 4;
	}
	GameSlot *targetSlot = m_slotList[m_targetSlot];
	if (!m_beenProbed && timeGetTime() >= m_nextPortSendTime)
	{
		AsciiString name;
		name.translate(targetSlot->m_name);
		if (m_unk0x24)
		{
			rva005A7974(get(m_localSlot), targetSlot);
			m_nextPortSendTime = timeGetTime() + g_00DD35B8;
		}
	}
	if (m_connectionState == 2)
	{
		if (!m_unk0x24)
		{
			UnsignedShort mangledPort;
			if (TheFirewallHelper != 0 && (mangledPort = TheFirewallHelper->getManglerResponse(m_packetID, 0)) != 0)
			{
				processManglerResponse(mangledPort);
				TheFirewallHelper->closeSpareSocket(m_spareSocketPort);
				m_spareSocketPort = 0;
			}
			else if (timeGetTime() >= m_manglerRetryTime)
			{
				++m_manglerRetries;
				if (m_manglerRetries > g_00DD35C0)
				{
					rva005A7974(get(m_localSlot), targetSlot);
				}
				else
				{
					if (TheFirewallHelper != 0)
						TheFirewallHelper->sendToManglerFromPort(m_manglerAddress, m_spareSocketPort, m_packetID, 4321, false);
					m_manglerRetryTime = timeGetTime() + g_00DD35BC;
				}
			}
		}
		if (!m_unk0x25)
		{
			if (timeGetTime() > m_timeoutTime)
			{
				setCurrentConnectionState(5);
				notifyConnectionToTargetFailed();
			}
		}
		if (m_unk0x25 && m_unk0x24)
			setCurrentConnectionState(3);
	}
	else if (m_connectionState == 3)
	{
		if (m_timeTillNextSend != (UnsignedInt)-1 && m_timeTillNextSend <= timeGetTime())
		{
			if (m_numRetries > m_maxNumRetriesAllowed)
			{
				setCurrentConnectionState(5);
				notifyConnectionToTargetFailed();
			}
			else
			{
				sendAProbeToTarget();
				++m_numRetries;
			}
		}
	}
	if (timeGetTime() > m_roundTimeout && m_connectionState != 4 && m_connectionState != 5)
	{
		setCurrentConnectionState(5);
		notifyConnectionToTargetFailed();
	}
	if (m_previousConnectionState != 4)
		TheFirewallHelper->flagNeedToRefresh(true);
	return m_connectionState;
}

