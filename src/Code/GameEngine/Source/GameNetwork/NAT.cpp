// FUNCTION: BFME2 0x005A854C size=282 name=?processManglerResponse@NAT@@QAEXG@Z evidence=N:ledger tier=A
void NAT::processManglerResponse(UnsignedShort mangledPort)
{
	GameSlot *targetSlot = m_slotList[m_targetSlot];
	if (targetSlot == 0)
	{
		setCurrentConnectionState(5);
		return;
	}
	Short delta = (Short)TheWritableGlobalData->m_firewallPortAllocationDelta;
	UnsignedShort sourcePort = m_spareSocketPort + 1;
	UnsignedShort returnPort = 0;
	UnsignedInt behavior = m_slotList[m_localSlot]->m_unk0x40;
	if (behavior & 0x10)
		returnPort = mangledPort + delta;
	else if (behavior & 0x40)
		returnPort = mangledPort + delta;
	else if (delta == 100)
		returnPort = sourcePort - m_spareSocketPort + mangledPort + 100;
	else if (delta == 0)
		returnPort = sourcePort;
	else
		returnPort = (mangledPort / delta + 1) * delta + sourcePort % delta;
	if (returnPort > 65535)
		returnPort -= 65535;
	if (returnPort < 1024)
		returnPort += 1024;
	BfmeNetAddress address;
	m_previousSourcePort = returnPort;
	if (!SetUDPSocketForSlot(sourcePort, m_targetSlot, &address))
	{
		probeMangler();
		return;
	}
	m_addresses[m_localSlot]->m_port = m_spareSocketPort + 1;
	rva005A7974(returnPort, targetSlot);
	if (m_unk0x25 != 0)
	{
		setCurrentConnectionState(3);
		m_transport->setDestAddrToSocket(m_targetSlot, m_addresses[m_targetSlot]);
	}
}

