// FUNCTION: BFME2 0x005A6EF2 size=640 name=?sendPings@NAT@@QAEXXZ evidence=N:ledger tier=A

void NAT::sendPings()
{
	UnsignedInt now = timeGetTime();

	for (Int i = 0; i < 8; ++i)
	{
		if (i == m_localSlot)
			continue;
		GameSlot *slot = m_slotList[i];
		if (slot == 0 || !slot->isHuman())
			continue;
		if (!m_schema.isConnectionDone(m_localSlot, i))
			continue;
		if (now <= (UnsignedInt)m_schema.getTimeToSendPing(i))
		{
			PortNegotiationPing *ping = (PortNegotiationPing *)m_schema.peekPing(m_localSlot, i);
			if (ping == 0)
				continue;
			if (!(ping->getOutstanding() >= 1.0 && ping->getFailures() < 2.0))
				continue;
		}
		if (!m_schema.sentAPingPacket(m_localSlot, i))
			continue;

		AsciiString pingStr;
		AsciiString tempStr;
		pingStr.format("PING%d %X %X", m_localSlot, m_schema.getActionID(m_localSlot, i), now);

		if (i == m_hostSlot)
		{
			for (UnsignedByte j = 0; j < 8; ++j)
			{
				if (j == m_localSlot)
					continue;
				GameSlot *other = m_slotList[j];
				if (other == 0 || !other->isHuman())
					continue;
				if (!m_schema.isConnectionDone(m_localSlot, j))
					continue;
				PortNegotiationPing *ping = (PortNegotiationPing *)m_schema.peekPing(m_localSlot, j);
				if (ping == 0)
					continue;
				if (ping->hasSamples() == 0.0f)
					continue;
				tempStr.format(" %X %3.0f", j, ping->getLatency());
				pingStr.concat(tempStr);
			}
		}
		else if (slot->isHuman() && m_schema.isConnectionDone(m_localSlot, i))
		{
			PortNegotiationPing *ping = (PortNegotiationPing *)m_schema.peekPing(m_localSlot, i);
			if (ping != 0 && ping->hasSamples() != 0.0f)
			{
				tempStr.format(" %X %3.0f", i, ping->getLatency());
				pingStr.concat(tempStr);
			}
		}

		m_transport->queueSend((NetPacketAddress *)m_addresses[i], (const UnsignedByte *)pingStr.str(), pingStr.getLength() + 1);
	}
}

