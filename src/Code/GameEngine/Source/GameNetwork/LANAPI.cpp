// FUNCTION: BFME2 0x0044B2EA size=290 name=?addGame@LANAPI@@IAEXPAVLANGameInfo@@@Z evidence=N:ledger tier=A
void LANAPI::addGame(LANGameInfo *game)
{
	if (!m_games)
	{
		m_games = game;
		game->setNext(NULL);
		return;
	}
	else
	{
		if (game->getName().compareNoCase(m_games->getName()) < 0)
		{
			game->setNext(m_games);
			m_games = game;
			return;
		}
		else
		{
			LANGameInfo *lANGameInfo = m_games;
			while (lANGameInfo->getNext() && lANGameInfo->getNext()->getName().compareNoCase(game->getName()) > 0)
			{
				lANGameInfo = lANGameInfo->getNext();
			}
			game->setNext(lANGameInfo->getNext());
			lANGameInfo->setNext(game);
			return;
		}
	}
}

// FUNCTION: BFME2 0x0044B40C size=143 name=?addPlayer@LANAPI@@IAEXPAVLANPlayer@@@Z evidence=N:ledger tier=A
void LANAPI::addPlayer(LANPlayer *player)
{
	if (m_lobbyPlayers == 0)
	{
		m_lobbyPlayers = player;
		player->setNext(0);
		return;
	}
	if (player->getName().compareNoCase(m_lobbyPlayers->getName()) < 0
		|| (player->getName().compareNoCase(m_lobbyPlayers->getName()) == 0 && player->getIP() < m_lobbyPlayers->getIP()))
	{
		player->setNext(m_lobbyPlayers);
		m_lobbyPlayers = player;
		return;
	}
	LANPlayer *current = m_lobbyPlayers;
	while (current->getNext() != 0
		&& (player->getName().compareNoCase(current->getNext()->getName()) > 0
			|| (player->getName().compareNoCase(current->getNext()->getName()) == 0 && player->getIP() > current->getNext()->getIP())))
		current = current->getNext();
	player->setNext(current->getNext());
	current->setNext(player);
}

// FUNCTION: BFME2 0x0044B49B size=191 name=?reset@LANAPI@@UAEXXZ evidence=N:ledger tier=A
void LANAPI::reset()
{
	if (m_inLobby)
	{
		LANMessage message;
		fillInLANMessage(&message);
		message.LANMessageType = LANMessage::MSG_REQUEST_LOBBY_LEAVE;
		sendMessage(&message, 0);
	}
	m_transport->update(0);

	LANGameInfo *game = m_games;
	while (game != 0)
	{
		LANGameInfo *deletable = game;
		game = game->m_next;
		::delete deletable;
	}

	LANPlayer *player = m_lobbyPlayers;
	while (player != 0)
	{
		LANPlayer *deletable = player;
		player = player->m_next;
		delete deletable;
	}

	m_games = 0;
	m_lobbyPlayers = 0;
	m_directConnectAddress = BfmeNetAddress();
	m_pendingAction = 0;
	m_expiration = 0;
	m_inLobby = true;
	m_isInLANMenu = true;
	if (TheGameInfo == m_currentGame)
		TheGameInfo = 0;
	m_currentGame = 0;
}

// FUNCTION: BFME2 0x0044B55A size=591 name=?RequestGameCreate@LANAPI@@UAEXVUnicodeString@@_N@Z evidence=N:ledger tier=A
void LANAPI::RequestGameCreate(UnicodeString gameName, Bool isDirectConnect)
{
	if ((!m_inLobby || m_currentGame != 0) && !isDirectConnect)
	{
		OnGameCreate(RET_BUSY);
		return;
	}

	if (m_pendingAction != ACT_NONE)
	{
		OnGameCreate(RET_BUSY);
		return;
	}

	m_inLobby = false;
	LANGameInfo *myGame = new LANGameInfo;
	myGame->reset();
	myGame->enterGame();

	UnicodeString name;
	name.format(L"%8.8X%8.8X", GetLocalAddress()->m_ip, myGame->getSeed());
	if (gameName.isEmpty())
		name.concat(m_name);
	else
		name.concat(gameName);

	while (name.getLength() > 16)
		name.removeLastChar();

	myGame->setName(name);

	LANGameSlot newSlot;
	GameSlotConnectInfo connectInfo;
	connectInfo.m_ip = 0;
	connectInfo.m_port = 0;
	newSlot.setState(SLOT_PLAYER, m_name, &connectInfo);
	BfmeNetAddress *localAddress = GetLocalAddress();
	newSlot.m_address = *localAddress;
	newSlot.m_lastHeard = 0;
	newSlot.setLogin(m_userName);
	newSlot.setHost(m_hostName);

	myGame->setSlot(0, newSlot);
	myGame->setNext(0);

	LANPreferences pref(0);
	AsciiString mapName = pref.rva0044D986();
	myGame->setMapForwarder(mapName);
	myGame->m_isDirectConnect = isDirectConnect;
	myGame->setLastHeard(timeGetTime());
	m_currentGame = myGame;

	addGame(myGame);
	OnGameCreate(RET_OK);
}

// FUNCTION: BFME2 0x0044B7A9 size=364 name=?RequestSetName@LANAPI@@UAEXVUnicodeString@@@Z evidence=N:ledger tier=B hypothesis:cohesion
void LANAPI::RequestSetName(UnicodeString newName)
{
	newName.trim();
	if (m_pendingAction != 0)
	{
		OnNameChange((UnsignedInt)GetLocalAddress(), newName);
		return;
	}

	m_lastResendTime = timeGetTime();

	if (m_inLobby && m_pendingAction == 0)
	{
		m_name = newName;
		LANMessage message;
		fillInLANMessage(&message);
		message.LANMessageType = LANMessage::MSG_LOBBY_ANNOUNCE;
		sendMessage(&message, 0);

		LANPlayer *player = LookupPlayer(GetLocalAddress());
		if (player == 0)
		{
			player = new LANPlayer;
			player->m_address = *GetLocalAddress();
		}
		else
		{
			removePlayer(player);
		}
		player->m_name = m_name;
		player->m_host.translate(m_hostName);
		player->m_login.translate(m_userName);
		player->m_lastHeard = timeGetTime();

		addPlayer(player);

		OnNameChange((UnsignedInt)&player->m_address, player->m_name);
	}
}

