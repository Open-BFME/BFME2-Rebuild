// FUNCTION: BFME2 0x0044B7A9 size=364 name=?RequestSetName@LANAPI@@UAEXVUnicodeString@@@Z evidence=N:ledger tier=B hypothesis:cohesion
void LANAPI::RequestSetName(UnicodeString newName)
{
	newName.trim();
	if (m_pendingAction != 0)
	{
		OnNameChange((UnsignedInt)GetLocalAddress(), newName);
		return;
	}

	m_lastResendTime = timeGetTime();

	if (m_inLobby && m_pendingAction == 0)
	{
		m_name = newName;
		LANMessage message;
		fillInLANMessage(&message);
		message.LANMessageType = LANMessage::MSG_LOBBY_ANNOUNCE;
		sendMessage(&message, 0);

		LANPlayer *player = LookupPlayer(GetLocalAddress());
		if (player == 0)
		{
			player = new LANPlayer;
			player->m_address = *GetLocalAddress();
		}
		else
		{
			removePlayer(player);
		}
		player->m_name = m_name;
		player->m_host.translate(m_hostName);
		player->m_login.translate(m_userName);
		player->m_lastHeard = timeGetTime();

		addPlayer(player);

		OnNameChange((UnsignedInt)&player->m_address, player->m_name);
	}
}

// FUNCTION: BFME2 0x0044B915 size=125 name=?LookupGame@LANAPI@@UAEPAVLANGameInfo@@VUnicodeString@@@Z evidence=N:ledger tier=B hypothesis:cohesion
LANGameInfo *LANAPI::LookupGame(UnicodeString gameName)
{
	LANGameInfo *game = m_games;
	while (game != 0 && game->getName().compare(gameName) != 0)
		game = game->m_next;
	return game;
}

