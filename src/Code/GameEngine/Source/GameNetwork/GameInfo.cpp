// FUNCTION: BFME2 0x0040052C size=599 name=?adjustSlotsForMap@GameInfo@@UAEXXZ evidence=N:ledger tier=A
void GameInfo::adjustSlotsForMap()
{
	const MapMetaData *md = TheMapCache->findMap(m_mapName);
	if (md != 0)
	{
		Int numPlayers = md->m_numPlayers;
		Int numPlayerSlots = 0;
		Int numHumanSlots = 0;
		Int i;

		for (i = 0; i < MAX_SLOTS; ++i)
		{
			GameSlot *gameSlot = getSlot(i);
			if (gameSlot->isOccupied())
			{
				++numPlayerSlots;
				if (gameSlot->isHuman())
					++numHumanSlots;
			}
		}

		for (i = 0; i < MAX_SLOTS; ++i)
		{
			GameSlot *slot = getSlot(i);
			if (numPlayers > numPlayerSlots)
			{
				if (!(slot->isOccupied()))
				{
					if (m_unk0x5C == 1)
					{
						if (numHumanSlots < 2)
						{
							GameSlot newSlot;
							GameSlotConnectInfo connectInfo;
							connectInfo.m_ip = 0;
							connectInfo.m_port = 0;
							newSlot.setState(SLOT_OPEN, UnicodeString::TheEmptyString, &connectInfo);
							setSlot(i, newSlot);
							++numHumanSlots;
						}
						else
						{
							GameSlot newSlot;
							GameSlotConnectInfo connectInfo;
							connectInfo.m_ip = 0;
							connectInfo.m_port = 0;
							newSlot.setState(SLOT_CLOSED, UnicodeString::TheEmptyString, &connectInfo);
							setSlot(i, newSlot);
						}
					}
					else
					{
						GameSlot newSlot;
						GameSlotConnectInfo connectInfo;
						connectInfo.m_ip = 0;
						connectInfo.m_port = 0;
						newSlot.setState(SLOT_OPEN, UnicodeString::TheEmptyString, &connectInfo);
						setSlot(i, newSlot);
						++numPlayerSlots;
					}
				}
			}
			else
			{
				if (!(slot->isOccupied()))
				{
					GameSlot newSlot;
					GameSlotConnectInfo connectInfo;
					connectInfo.m_ip = 0;
					connectInfo.m_port = 0;
					newSlot.setState(SLOT_CLOSED, UnicodeString::TheEmptyString, &connectInfo);
					setSlot(i, newSlot);
				}
			}
		}
	}
}


