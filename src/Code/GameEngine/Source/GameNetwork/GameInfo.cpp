static Bool isSlotLocalAlly(const GameSlot *candidate)
{
	Int thatSeat = findSlotIndex(candidate);
	Int thisSeat = TheGameInfo->getLocalSlotNum();
	const GameSlot *mine = TheGameInfo->getConstSlot(thisSeat);
	if (thatSeat < 0 || thisSeat < 0)
		return false;
	if (thatSeat == thisSeat)
		return true;
	Int groupId = candidate->m_teamNumber;
	if (groupId == mine->m_teamNumber && groupId >= 0)
		return true;
	return mine->m_origPlayerTemplate == -2 ? true : false;
}

