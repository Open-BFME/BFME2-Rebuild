// FUNCTION: BFME2 0x003FFC28 size=399 name=?setState@GameSlot@@QAEXW4SlotState@@VUnicodeString@@PBUGameSlotConnectInfo@@@Z evidence=N:ledger tier=A
void GameSlot::setState(SlotState state, UnicodeString name, const GameSlotConnectInfo *connectInfo)
{
	if (!(isAI() && (state == SLOT_EASY_AI || state == SLOT_MED_AI || state == SLOT_HARD_AI || state == SLOT_BRUTAL_AI)))
	{
		m_color = -1;
		m_startPos = -1;
		m_unk0x14 = -1;
		m_playerTemplate = -2;
		m_teamNumber = -1;
		m_unk0x20 = 0;
	}
	if (state == SLOT_PLAYER)
	{
		reset();
		m_state = state;
		m_name = name;
	}
	else
	{
		m_state = state;
		m_isAccepted = true;
		m_hasMap = true;
		switch (state)
		{
		case SLOT_OPEN:
			m_name = TheGameText->fetch("GUI:Open");
			break;
		case SLOT_EASY_AI:
			m_name = TheGameText->fetch("GUI:EasyAI");
			break;
		case SLOT_MED_AI:
			m_name = TheGameText->fetch("GUI:MediumAI");
			break;
		case SLOT_HARD_AI:
			m_name = TheGameText->fetch("GUI:HardAI");
			break;
		case SLOT_BRUTAL_AI:
			m_name = TheGameText->fetch("GUI:BrutalAI");
			break;
		case SLOT_CLOSED:
		default:
			m_name = TheGameText->fetch("GUI:Closed");
			break;
		}
	}
	m_address = *(const BfmeNetAddress *)connectInfo;
}


