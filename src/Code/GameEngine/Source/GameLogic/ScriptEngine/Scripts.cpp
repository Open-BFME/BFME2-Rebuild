template <class T> Int ScriptTable<T>::find(const AsciiString &name) const
{
	UnsignedInt position = lowerBound(name);
	if (position < m_order.size())
	{
		Int index = m_order[position];
		if (m_entries[index].m_name.compare(name) == 0)
			return index;
	}
	return -1;
}

