Bool Script::parse(DataChunkInput &file, unsigned short version)
{
	m_scriptName = file.readAsciiString();
	m_comment = file.readAsciiString();
	m_conditionComment = file.readAsciiString();
	Bool active = file.readByte() != 0;
	m_activeNow = active;
	m_isActive = active;
	m_isOneShot = file.readByte() != 0;
	m_easy = file.readByte() != 0;
	m_normal = file.readByte() != 0;
	m_hard = file.readByte() != 0;
	m_isSubroutine = file.readByte() != 0;
	if (version >= 2)
		m_delayEvaluationSeconds = file.readInt();
	if (version >= 3)
		m_record.read(file, version);
	if (version >= 4)
		m_phaseMask = readScriptPlayerMask(file);
	else
		m_phaseMask = *(const ScriptPhaseMask *)&g_Va00E02D64;
	static const char scriptLabel[] = "Script";
	file.registerParser(AsciiString("OrCondition"), AsciiString(scriptLabel), OrCondition::ParseOrConditionDataChunk, 0);
	file.registerParser(AsciiString("ScriptAction"), AsciiString(scriptLabel), ScriptAction::ParseActionDataChunk, 0);
	file.registerParser(AsciiString("ScriptActionFalse"), AsciiString(scriptLabel), ScriptAction::ParseActionFalseDataChunk, 0);
	return file.parse(this);
}

