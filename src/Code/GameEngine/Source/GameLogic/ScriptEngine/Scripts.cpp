{
	_STL::deque<ScriptGroupLink **> slots;
	for (ScriptGroupLink **slot = sourceHead; *slot; slot = &(*slot)->m_next)
		slots.push_back(slot);
	while (!slots.empty())
	{
		doTakeGroup(source, slots.back(), destHead);
		slots.pop_back();
	}
}

