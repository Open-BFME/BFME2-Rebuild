// FUNCTION: BFME2 0x003B66D8 size=131 name=?deallocateEntry@Rva003B573E@@QAEXH@Z evidence=?:placeholder tier=A
template <class T> void ScriptTable<T>::deallocateEntry(Int index)
{
	Entry &entry = m_entries[index];
	--entry.m_depth;
	entry.m_flagged = true;
	if (entry.m_versions == 0)
	{
		Int position = lowerBound(entry.m_name);
		if (entry.m_next != -1)
			m_entries[entry.m_next].m_prev = entry.m_prev;
		if (entry.m_prev != -1)
			m_entries[entry.m_prev].m_next = entry.m_next;
		else
			m_liveHead = entry.m_next;
		entry.m_next = m_freeHead;
		m_freeHead = index;
		entry.m_name.clear();
		m_order.erase(m_order.begin() + position);
	}
}

