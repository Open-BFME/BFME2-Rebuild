// FUNCTION: BFME2 0x003B6AB2 size=445 name=?getUiText@Script@@QAE?AVAsciiString@@XZ evidence=N:ledger tier=A
AsciiString Script::getUiText()
{
	AsciiString uiText("*** IF ***\r\n");
	OrCondition *pOr = m_condition;
	Int count = 0;
	while (pOr)
	{
		Condition *pCond = pOr->getFirstAndCondition();
		if (count > 0)
			uiText.concat("  *** OR ***\r\n");
		count = 0;
		while (pCond)
		{
			if (count > 0)
				uiText.concat("    *AND* ");
			else
				uiText.concat("    ");
			if (!pCond->m_flag4C)
				uiText.concat(" (DISABLED) ");
			if (pCond->m_b4D)
				uiText.concat(" NOT ");
			uiText.concat(pCond->getUiText());
			uiText.concat("\r\n");
			pCond = pCond->getNext();
			count++;
		}
		pOr = pOr->getNextOrCondition();
	}
	uiText.concat("*** THEN ***\r\n");
	ScriptAction *pAction = m_actions[0];
	while (pAction)
	{
		uiText.concat("  ");
		uiText.concat(pAction->getUiText());
		uiText.concat("\r\n");
		pAction = pAction->getNext();
	}
	pAction = m_actions[1];
	if (pAction)
	{
		uiText.concat("*** ELSE ***\r\n");
		while (pAction)
		{
			uiText.concat("  ");
			uiText.concat(pAction->getUiText());
			uiText.concat("\r\n");
			pAction = pAction->getNext();
		}
	}
	return uiText;
}

