void ScriptList::deleteScriptRef(void *head, ScriptLink *link)
{
	// the chain's head slot is walked as if it were a link: its next pointer is the first word
	ScriptLink *node = (ScriptLink *)&((ScriptListBase *)head)->m_firstScript;
	for (;;)
	{
		if (node->m_next == link)
		{
			node->m_next = link->m_next;
			link->m_next = 0;
			break;
		}
		node = node->m_next;
		if (!node)
			break;
	}
	m_scripts.popVersion(link->m_index);
	delete link;
}

