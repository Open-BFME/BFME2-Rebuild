// FUNCTION: BFME2 0x003B6D06 size=140 name=?duplicate@OrCondition@@QBEPAV1@XZ evidence=N:ledger tier=A
OrCondition *OrCondition::duplicate() const
{
	OrCondition *pNew = ::new OrCondition;
	if (m_firstAnd)
		pNew->m_firstAnd = m_firstAnd->duplicate();
	OrCondition *pLink = m_nextOrCondition;
	OrCondition *pCur = pNew;
	while (pLink)
	{
		pCur->m_nextOrCondition = ::new OrCondition;
		pCur = pCur->m_nextOrCondition;
		if (pLink->m_firstAnd)
			pCur->m_firstAnd = pLink->m_firstAnd->duplicate();
		pLink = pLink->m_nextOrCondition;
	}
	return pNew;
}

// FUNCTION: BFME2 0x003B6D92 size=709 name=?ParseConditionDataChunk@Condition@@SA_NAAVDataChunkInput@@PAUDataChunkInfo@@PAX@Z evidence=N:ledger tier=A

Bool Condition::ParseConditionDataChunk(DataChunkInput &file, DataChunkInfo *info, void *userData)
{
	Condition *pCondition = ::new Condition;
	OrCondition *pOr = (OrCondition *)userData;
	pCondition->m_conditionType = file.readInt();
	const ConditionTemplate *ct = TheScriptEngine->getConditionTemplate(pCondition->m_conditionType);
	Bool match = false;
	if (info->m_version >= 4)
	{
		NameKeyType key = file.readNameKey();
		if (ct && ct->m_internalNameKey == key)
		{
			match = true;
		}
		else
		{
			for (Int i = 0; i < Condition::NUM_ITEMS; i++)
			{
				ct = TheScriptEngine->getConditionTemplate(i);
				if (key == ct->m_internalNameKey)
				{
					match = true;
					pCondition->m_conditionType = i;
					break;
				}
			}
		}
	}
	pCondition->m_numParms = file.readInt();
	for (Int i = 0; i < pCondition->m_numParms; i++)
	{
		Parameter *parameter = Parameter::ReadParameter(file);
		pCondition->m_parms[i] = parameter;
		if (parameter->getParameterType() == Parameter::OBJECT_TYPE && ct->m_numParameters > i &&
			ct->getParameterType(i) == Parameter::OBJECT_TYPE_LIST)
		{
			parameter->convertToObjectTypeList();
		}
	}
	if (info->m_version >= 5)
	{
		pCondition->m_flag4C = file.readInt() != 0;
		pCondition->m_b4D = file.readInt() != 0;
	}
	else
	{
		pCondition->m_flag4C = true;
		pCondition->m_b4D = false;
	}
	if (!match)
	{
		// the name and number do not agree and the name is unknown: make it a false condition
		ct = TheScriptEngine->getConditionTemplate(0);
		pCondition->m_conditionType = Condition::CONDITION_FALSE;
		while (pCondition->m_numParms > 0)
		{
			pCondition->m_numParms--;
			Parameter *parameter = pCondition->m_parms[pCondition->m_numParms];
			if (parameter)
				delete parameter;
		}
	}
	if (file.getChunkVersion() < 2)
	{
		for (Int j = 0; ParameterChangesVer2[j] != -1; ++j)
		{
			if (pCondition->m_conditionType == ParameterChangesVer2[j])
			{
				pCondition->m_parms[pCondition->m_numParms] = ::new Parameter(Parameter::SURFACES_ALLOWED, 3);
				pCondition->m_numParms = 3;
			}
		}
	}
	else if (file.getChunkVersion() < 6)
	{
		for (Int j = 0; ParameterChangesVer2[j] != -1; ++j)
		{
			if (pCondition->m_conditionType == ParameterChangesVer2[j])
			{
				delete pCondition->m_parms[pCondition->m_numParms - 1];
				pCondition->m_parms[pCondition->m_numParms - 1] = ::new Parameter(Parameter::SURFACES_ALLOWED, 0);
			}
		}
	}
	if (pCondition->m_conditionType == Condition::SKIRMISH_SPECIAL_POWER_READY && pCondition->m_numParms == 1)
	{
		pCondition->m_numParms = 2;
		pCondition->m_parms[1] = pCondition->m_parms[0];
		pCondition->m_parms[0] = ::new Parameter(Parameter::SIDE, 0);
		pCondition->m_parms[0]->friend_setString(AsciiString("<This Player>"));
	}
	if (ct->m_numParameters != pCondition->m_numParms)
	{
		ct = TheScriptEngine->getConditionTemplate(0);
		pCondition->m_conditionType = Condition::CONDITION_FALSE;
		while (pCondition->m_numParms > 0)
		{
			pCondition->m_numParms--;
			Parameter *parameter = pCondition->m_parms[pCondition->m_numParms];
			if (parameter)
				delete parameter;
		}
	}
	Condition *pLast = pOr->getFirstAndCondition();
	while (pLast && pLast->getNext())
		pLast = pLast->getNext();
	if (pLast)
		pLast->setNextCondition(pCondition);
	else
		pOr->setFirstAndCondition(pCondition);
	return true;
}

