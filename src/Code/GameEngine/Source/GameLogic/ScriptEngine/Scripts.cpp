// FUNCTION: BFME2 0x003B56DC size=98 name=?rva003B56DC@Rva003B573E@@QAEXXZ evidence=?:placeholder tier=A
template <class T> void ScriptTable<T>::flattenAll()
{
	for (Int i = m_liveHead; i != -1; i = m_entries[i].m_next)
	{
		Entry &entry = m_entries[i];
		Version *newest = static_cast<Version *>(entry.m_versions);
		while (newest->m_older)
		{
			ScriptTableVersion *rest = newest->m_older->m_older;
			Version *old = static_cast<Version *>(newest->m_older);
			delete old;
			newest->m_older = rest;
		}
		entry.m_depth = 1;
	}
}

