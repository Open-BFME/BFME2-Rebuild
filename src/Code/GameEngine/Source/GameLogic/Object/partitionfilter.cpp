// FUNCTION: BFME2 0x00261B7E size=125 name=?allow@PartitionFilterRejectBuildings@@UAE_NPAVObject@@@Z evidence=N:ledger tier=B hypothesis:Z
bool PartitionFilterRejectBuildings::allow(Object *other)
{
	// this filter allows all non-buildings
	if (!other->getTemplate()->isKindOf(KINDOF_STRUCTURE))
		return true;
	if (other->getTemplate()->isKindOf(KINDOF_MINE))
		return true;

	const Player *myPlayer = m_obj->getControllingPlayer();
	if (!myPlayer)
		return false;

	// the controlling player of the other object
	ContainModuleInterface *contain = other->getContain();
	const Player *otherPlayer = contain ? contain->getApparentControllingPlayer(myPlayer) : 0;
	if (!otherPlayer)
		otherPlayer = other->getControllingPlayer();
	if (!otherPlayer)
		return false;

	// a computer-controlled opponent auto-acquires enemy buildings
	if (m_flag)
		return true;

	// don't reject base defenses
	if (other->getTemplate()->isKindOf(KINDOF_FS_BASE_DEFENSE))
		return true;

	// don't reject garrisoned buildings that can attack
	if (other->getContain() != 0 && other->isAbleToAttack())
		return true;
	return false;
}

