	if (m_curLocomotor == NULL)
	{
		return FALSE;	// No loco, so we aren't moving.
	}

	// Cur loco is air, so not ground.
	if (m_curLocomotor->m_template->m_surfaces & 8)
	{
		return FALSE;
	}

