// FUNCTION: BFME2 0x003A4BFD size=177 name=?update@LifetimeUpdate@@UAE?AW4UpdateSleepTime@@XZ evidence=N:ledger
UpdateSleepTime LifetimeUpdate::update()
{
	const LifetimeUpdateModuleData *data = (const LifetimeUpdateModuleData *)getModuleData();
	Object *obj = getObject();
	if (obj->testModelConditionState((ModelConditionFlagType)0x9A))
		return UPDATE_SLEEP_NONE;
	if (data->m_creditKiller)
	{
		BodyModuleInterface **bodySlot = &obj->m_body;
		const DamageInfo *lastDamage = (*bodySlot)->getLastDamageInfo();
		ObjectID killerID = lastDamage ? (*bodySlot)->getLastDamageInfo()->in.m_sourceID : (ObjectID)0;
		Object *killer = TheGameLogic->findObjectByID(killerID);
		if (killer)
			killer->report(obj, 1);
	}
	else
	{
		Player *owner = obj->getControllingPlayer();
		ScoreKeeper *sk = owner->getScoreKeeper();
		Bool wasEnabled = sk->m_enabled;
		sk->setEnabled(false);
		sk->addObjectBuilt(obj, -1);
		sk->setEnabled(wasEnabled);
	}
	obj->kill(DAMAGE_UNRESISTABLE, data->m_deathType);
	return UPDATE_SLEEP_FOREVER;
}

