// FUNCTION: BFME2 0x004D8DEA size=194 name=?updateTurretAI@TurretAI@@QAE?AW4UpdateSleepTime@@XZ evidence=N:ledger tier=B hypothesis:cohesion
UpdateSleepTime TurretAI::updateTurretAI()
{
	UnsignedInt now = TheGameLogic->getFrame();
	if (m_sleepUntil != 0 && now < m_sleepUntil)
		return (UpdateSleepTime)(m_sleepUntil - now);

	UpdateSleepTime result = UPDATE_SLEEP_FOREVER;
	if (!m_firesWhileTurning || m_continuousFireExpirationFrame <= now)
	{
		m_playRotSound = false;
		m_playPitchSound = false;
	}

	if (m_enabled || m_turretStateMachine->getCurrentStateID() == TURRETAI_RECENTER)
	{
		m_didFire = false;
		StateReturnType status = m_turretStateMachine->updateStateMachine();
		if (m_turretStateMachine == 0)
			return UPDATE_SLEEP_NONE;

		if (m_didFire)
		{
			m_enableSweepUntil = now + 3;
			m_continuousFireExpirationFrame = now + 3;
		}

		if (!m_playRotSound && !m_playPitchSound)
			stopRotOrPitchSound();
		else
			startRotOrPitchSound();

		if (status > 0)
		{
			if (status < STATE_SLEEP_FOREVER)
				result = (UpdateSleepTime)status;
		}
		else
			result = UPDATE_SLEEP_NONE;
	}

	m_sleepUntil = result + now;
	return result;
}

