// FUNCTION: BFME2 0x004D8990 size=431 name=?friend_turnTowardsAngle@TurretAI@@QAE_NMMM@Z evidence=N:ledger tier=A
Bool TurretAI::friend_turnTowardsAngle(Real desiredAngle, Real rateModifier, Real relThresh)
{
	desiredAngle = normalizeAngle(desiredAngle);
	Real targetAngle = desiredAngle;

	Real deflectionA = m_data->m_maxDeflectionCW;
	Real deflectionB = m_data->m_maxDeflectionCCW;
	if (deflectionB + deflectionA < 6.2831855f)
	{
		Real natural = getNaturalTurretAngle();
		Real lo = normalizeAngle(natural - deflectionA);
		Real hi = normalizeAngle(natural + deflectionB);
		if (lo > hi)
		{
			if (lo > desiredAngle && desiredAngle > hi)
				targetAngle = natural;
		}
		else
		{
			if (lo > desiredAngle || desiredAngle > hi)
				targetAngle = natural;
		}
	}

	Real origAngle = m_angle;
	Real actualAngle = origAngle;
	Real turnRate = rateModifier * m_data->m_turnRate;
	Real angleDiff = normalizeAngle(targetAngle - actualAngle);

	if (fabs(angleDiff) < turnRate)
	{
		actualAngle = targetAngle;
		m_owner->clearModelConditionState((UnsignedInt)58);
	}
	else
	{
		if (angleDiff > 0)
			actualAngle += turnRate;
		else
			actualAngle -= turnRate;
		m_owner->setModelConditionState((ModelConditionFlagType)58);
		m_playRotSound = true;
	}

	m_angle = normalizeAngle(actualAngle);

	if (m_angle != origAngle)
		m_owner->reactToTurretChange(m_whichTurret, origAngle, m_pitch);

	Bool aligned = fabs(m_angle - desiredAngle) <= relThresh;
	return aligned;
}

