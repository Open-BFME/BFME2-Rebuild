// FUNCTION: BFME2 0x00545F80 size=129 name=?findBestTunnel@@YAPAVObject@@PAVPlayer@@PBUCoord3D@@@Z evidence=N:ledger
// Retail passes the player in eax and the position in ebx: a file static whose
// three call sites (0x00546624, 0x005466F4, 0x00546748) are all in this unit.
static Object *findBestTunnel(Player *player, const Coord3D *from)
{
	if (!player)
		return NULL;
	// Nearest tunnel of the player's network in the ground plane.
	Object *closest = NULL;
	Real closestSqr = 0.0f;
	std::list<ObjectID> &ids = player->m_tunnelSystem->m_tunnelIDs;
	for (std::list<ObjectID>::iterator pos = ids.begin(), last = ids.end(); pos != last; ++pos)
	{
		Object *candidate = TheGameLogic->findObjectByID(*pos);
		if (!candidate)
			continue;
		Real offX = candidate->getPosition()->x - from->x;
		Real offY = candidate->getPosition()->y - from->y;
		Real lenSqr = offX * offX + offY * offY;
		if (closest == NULL || lenSqr < closestSqr)
		{
			closestSqr = lenSqr;
			closest = candidate;
		}
	}
	return closest;
}

