// FUNCTION: BFME2 0x0054665B size=258 name=?update@AITNGuardIdleState@@UAE?AW4StateReturnType@@XZ evidence=N:ledger
StateReturnType AITNGuardIdleState::update()
{
	// Between scans, sleep until the next one is due.
	UnsignedInt frame = TheGameLogic->getFrame();
	if (frame < m_nextEnemyScanTime)
		return (StateReturnType)(m_nextEnemyScanTime - frame);
	m_nextEnemyScanTime = frame + TheAI->getAiData()->m_guardEnemyScanRate;
	AIUpdateInterface *ownerAI = getMachineOwner()->getAI();
	ownerAI->friend_setGoalObject(NULL);
	Object *self = getMachineOwner();
	if (self->getAI()->getCrateID() != INVALID_ID)
	{
		getMachine()->setState(5004);	// the machine's crate-pickup state
		return (StateReturnType)(m_nextEnemyScanTime - frame);
	}
	Bool foundTarget = getGuardMachine()->lookForInnerTarget();
	if (foundTarget)
	{
		AITNGuardMachine *machine = getGuardMachine();
		Object *nemesis = TheGameLogic->findObjectByID(machine->getNemesisID());
		if (nemesis)
		{
			if (machine->getOwner()->getContainedBy())
			{
				Object *tunnel = findBestTunnel(self->getControllingPlayer(), nemesis->getPosition());
				ExitInterface *exitInterface = tunnel->getContain() ? tunnel->getContain()->getContainExitInterface() : NULL;
				if (!exitInterface)
					return STATE_FAILURE;
				if (!exitInterface->isExitBusy())
					exitInterface->exitObjectInAHurry(getMachineOwner());
			}
			else
				return STATE_SUCCESS;
		}
		return STATE_CONTINUE;
	}

	if (self->getContainedBy() == NULL && findBestTunnel(self->getControllingPlayer(), self->getPosition()) != NULL)
		return STATE_FAILURE;
	return (StateReturnType)(m_nextEnemyScanTime - frame);
}

