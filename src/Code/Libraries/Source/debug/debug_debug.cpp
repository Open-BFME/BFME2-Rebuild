// FUNCTION: BFME2 0x00039480 size=135 name=?SimpleMatch@Debug@@SA_NPBD0@Z evidence=N:ledger tier=A
bool Debug::SimpleMatch(const char *str, const char *pattern)
{
	while (*str && *pattern)
	{
		if (*pattern == '*')
		{
			pattern++;
			while (*str)
				if (SimpleMatch(str++, pattern))
					return true;
			return *str == *pattern;
		}
		else
		{
			char c = *str++;
			if (c >= 'A' && c <= 'Z')
				c += 'a' - 'A';
			if (c != *pattern++)
				return false;
		}
	}

	return *str == *pattern;
}

