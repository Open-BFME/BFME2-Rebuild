	// effectively. If character dump is enabled then an additional space is needed (64 chars then).
	unsigned itemPerLine = (dump.m_withChars ? 64 : 65) / (1 + 2 * dump.m_bytePerItem + (dump.m_withChars ? 1 : 0));
	if (!itemPerLine)
		itemPerLine = 1;

