// FUNCTION: BFME2 0x0003B670 size=134 name=?ExecuteFrameCommands@Debug@@UAEXH@Z evidence=N:ledger tier=A
void Debug::ExecuteFrameCommands(int frame)
{
	while (numFrameCommands > 0)
	{
		// the next command to run is the last one in the list
		if (frameCommands[numFrameCommands - 1].frame > frame)
			break;
		--numFrameCommands;
		const char *cmd = frameCommands[numFrameCommands].command;

		// the command may carry a group prefix: look for the colon
		unsigned int len = strlen(cmd);
		const char *p = cmd;
		while (len > 0 && *p != ':')
		{
			--len;
			++p;
		}
		if (len > 1)
			ExecCommand(p + 1, p + len);
		DebugFreeMemory((void *)cmd);
	}
}

// FUNCTION: BFME2 0x0003B700 size=228 name=?Update@Debug@@UAEXXZ evidence=N:ledger tier=A
void Debug::Update()
{
	// check all existing IO interfaces
	for (IOFactoryListEntry *cur = firstIOFactory; cur; cur = cur->next)
	{
		if (!cur->io)
			continue;

		// any input?
		bool hadInput = false;
		for (;;)
		{
			if (cur->inputAlloc - cur->inputUsed < 64)
				// must grow input buffer...
				cur->input = (char *)DebugReAllocMemory(cur->input, (cur->inputAlloc += 64) + 1);
			int numChars = cur->io->Read(cur->input + cur->inputUsed, cur->inputAlloc - cur->inputUsed);
			if (!numChars)
				break;

			cur->inputUsed += numChars;
			cur->input[cur->inputUsed] = 0;
			hadInput = true;
		}

		if (!hadInput)
			// skip then
			continue;

		// else look for completed commands and try to process them
		for (;;)
		{
			char *p = strchr(cur->input, '\n');
			if (!p)
				break;

			ExecCommand(cur->input, p);
			strcpy(cur->input, p + 1);
			cur->inputUsed = strlen(cur->input);
		}
	}
}
