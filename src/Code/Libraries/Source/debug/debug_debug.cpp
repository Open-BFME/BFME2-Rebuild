// FUNCTION: BFME2 0x00039720 size=173 name=?ScheduleFrameCommand@Debug@@AAEIHPBD@Z evidence=N:ledger tier=A
unsigned int Debug::ScheduleFrameCommand(int frame, const char *command)
{
	// grow the list if necessary
	if (numFrameCommands == frameCommandsAlloc)
	{
		frameCommandsAlloc += 16;
		frameCommands = (FrameCommand *)DebugReAllocMemory(frameCommands, frameCommandsAlloc * sizeof(FrameCommand));
	}

	// find the insertion position (the list is sorted by descending frame)
	unsigned int k = 0;
	for (; k < numFrameCommands; k++)
		if (frame >= frameCommands[k].frame)
			break;
	if (k < numFrameCommands)
		memmove(frameCommands + k + 1, frameCommands + k, (numFrameCommands - k) * sizeof(FrameCommand));

	frameCommands[k].frame = frame;
	frameCommands[k].command = command;
	return ++numFrameCommands;
}

