{
	WaitForSingleObject(m_mutex, 100);

	// anything to flush first?
	if (curType != DebugIOInterface::MAX && (curType != DebugIOInterface::Log || m_threadId != GetCurrentThreadId()))
		Debug::FlushOutput();

	// set new output
	curFrameEntry = Debug::GetFrameEntry(curStackFrame, FrameTypeLog, fileOrGroup, 0);
	if (curFrameEntry->status == NoSkip || curFrameEntry->status == 3 || curFrameEntry->status == Unknown)
	{
		SetPrefixAndRadix("", 10);
		++curFrameEntry->hits;

		// we're doing all this extra work so that DLOGs can be spread across
		// multiple calls
		if (curType == DebugIOInterface::Log && strcmp(curSource, curFrameEntry->fileOrGroup))
			Debug::FlushOutput();

		if (curType != DebugIOInterface::Log)
			Debug::StartOutput(DebugIOInterface::Log, "%s", curFrameEntry->fileOrGroup);
	}
	else if (curType != DebugIOInterface::MAX)
		Debug::FlushOutput();

	return *this;
}

