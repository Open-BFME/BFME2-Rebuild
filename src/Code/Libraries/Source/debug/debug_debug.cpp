// FUNCTION: BFME2 0x0003A750 size=334 name=?CheckBegin@Debug@@UAEAAV1@PBDHH0@Z evidence=N:ledger tier=A
Debug &Debug::CheckBegin(const char *file, int line, int reserved, const char *expr)
{
	// anything to flush first?
	if (curType != DebugIOInterface::MAX)
		Debug::FlushOutput();

	// set new output
	curFrameEntry = Debug::GetFrameEntry(curStackFrame, FrameTypeAssert, file, line);
	if (curFrameEntry->status == NoSkip || curFrameEntry->status == 3 || curFrameEntry->status == Unknown)
	{
		SetPrefixAndRadix("", 10);
		Debug::StartOutput(DebugIOInterface::Assert, "%s(%i)", curFrameEntry->fileOrGroup, curFrameEntry->line);
		++curFrameEntry->hits;

		// if there is a \code\ section in the filename truncate
		// everything before that (including \code\)
		const char *p = strstr(file, "\\code\\");
		p = p ? p + 6 : file;

		char timeString[129];
		GetTimeFormatA(0x400, 0, 0, 0, timeString, 128);
		timeString[128] = 0;

		*theDebug << "\n" << RepeatChar('=', 80) << "\nAssertion failed in " << p << ", line " << line
				  << " at " << timeString << ",\nexpression " << expr;
	}

	return *theDebug;
}

