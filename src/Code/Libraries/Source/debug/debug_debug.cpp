// FUNCTION: BFME2 0x00038EE0 size=266 name=?GetInput@Debug@@UAEHPADHPA_N@Z evidence=N:ledger tier=A
int Debug::GetInput(char *buf, int size, bool *structured)
{
	for (IOFactoryListEntry *cur = firstIOFactory; cur; cur = cur->next)
	{
		if (!cur->io)
			continue;

		bool gotData = false;
		if (!cur->io->CanRead())
			continue;

		*structured = true;
		for (;;)
		{
			// make room for at least 64 more characters
			if (cur->inputAlloc - cur->inputUsed < 0x40)
			{
				cur->inputAlloc += 0x40;
				cur->input = (char *)DebugReAllocMemory(cur->input, cur->inputAlloc + 1);
			}

			int read = cur->io->Read(cur->input + cur->inputUsed, cur->inputAlloc - cur->inputUsed);
			if (!read)
				break;
			cur->inputUsed += read;
			cur->input[cur->inputUsed] = 0;
			gotData = true;
		}

		if (gotData)
		{
			*structured = true;
			char *eol = strchr(cur->input, '\n');
			if (eol)
			{
				int len = eol - cur->input;
				if (len > size - 1)
					len = size - 1;
				strncpy(buf, cur->input, len);
				buf[len] = 0;
				strcpy(cur->input, eol + 1);
				cur->inputUsed = strlen(cur->input);
				return len;
			}
		}
	}

	return 0;
}

