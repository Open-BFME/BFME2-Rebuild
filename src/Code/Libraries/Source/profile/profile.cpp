	if (active)
	{
		m_frameNames[k].highIndex = ProfileId::FrameStart();
		m_frameNames[k].funcIndex = ProfileFuncLevelTracer::FrameStart();
	}
	else
	{
		m_frameNames[k].index0C = -1;
		m_frameNames[k].highIndex = -1;
		m_frameNames[k].funcIndex = -1;
	}
