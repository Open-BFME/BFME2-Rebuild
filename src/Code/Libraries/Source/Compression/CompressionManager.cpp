	{
		Int slen = srcLen - 8;
		Int ret = REF_decode(dest, src+8, &slen);
		if (ret)
			return ret;
		else
			return 0;
	}

	if (compType == COMPRESSION_NOXLZH)
	{
		Bool ret = DecompressMemory((void *)(src+8), srcLen-8, dest, destLen);
		if (ret)
			return destLen;
		else
			return 0;
	}

