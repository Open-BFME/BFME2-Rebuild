int Cftp::AsyncGetHostByName(char * szName, struct sockaddr_in &address )
{
	static int            stat = 0;
	static unsigned long  threadId;

	if( stat == 0 )
	{
		/* Kick off gethostname thread */
		gThreadFlag = 0;
		memset(&gThreadAddress,0,sizeof(gThreadAddress));

		if( CreateThread( NULL, 0, (LPTHREAD_START_ROUTINE)resolveHostAddress, szName, 0, &threadId ) == NULL )
		{
			return( FTP_FAILED );
		}

		stat = 1;
	}

	if( stat == 1 )
	{
		if( gThreadFlag )
		{
			/* Thread finished */
			address = gThreadAddress;
			address.sin_family=AF_INET;
			stat = 0;
			return( FTP_SUCCEEDED );
		}
	}

	return( FTP_TRYING );
}

