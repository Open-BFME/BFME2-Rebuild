// ArmorSetType.h: the bit indices of an object's armor set flags (BitFlags<21>, ActiveBody +0xF0).
// Target facts: the INI name table of that instantiation is at VA 0x00DBAA40, 21 entries in this order
// (VETERAN, ELITE, HERO, PLAYER_UPGRADE, WEAK_VERSUS_BASEDEFENSES, ALTERNATE_FORMATION, MOUNTED,
// PLAYER_UPGRADE_2, PLAYER_UPGRADE_3, UNBESIEGEABLE, AS_TOWER, CREATE_A_HERO_01 .. CREATE_A_HERO_10);
// ActiveBody::onVeterancyLevelChanged 0x004BE47D sets and clears the first three by their indices.
#pragma once
#ifndef BFME2_ARMORSETTYPE_H
#define BFME2_ARMORSETTYPE_H

#include "Common/BitFlags.h"

enum ArmorSetType
{
	ARMORSET_VETERAN = 0,
	ARMORSET_ELITE = 1,
	ARMORSET_HERO = 2,
	ARMORSET_PLAYER_UPGRADE = 3,
	ARMORSET_WEAK_VERSUS_BASEDEFENSES = 4,
	ARMORSET_ALTERNATE_FORMATION = 5,
	ARMORSET_MOUNTED = 6,
	ARMORSET_PLAYER_UPGRADE_2 = 7,
	ARMORSET_PLAYER_UPGRADE_3 = 8,
	ARMORSET_UNBESIEGEABLE = 9,
	ARMORSET_AS_TOWER = 10,
	ARMORSET_CREATE_A_HERO_01 = 11,
	ARMORSET_CREATE_A_HERO_02 = 12,
	ARMORSET_CREATE_A_HERO_03 = 13,
	ARMORSET_CREATE_A_HERO_04 = 14,
	ARMORSET_CREATE_A_HERO_05 = 15,
	ARMORSET_CREATE_A_HERO_06 = 16,
	ARMORSET_CREATE_A_HERO_07 = 17,
	ARMORSET_CREATE_A_HERO_08 = 18,
	ARMORSET_CREATE_A_HERO_09 = 19,
	ARMORSET_CREATE_A_HERO_10 = 20,
	ARMORSET_COUNT = 21
};

typedef BitFlags<21> ArmorSetFlags;

#endif
